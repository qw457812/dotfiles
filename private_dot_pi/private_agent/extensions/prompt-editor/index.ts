import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import {
  getAgentDir,
  type ExtensionAPI,
  type ExtensionUIContext,
} from "@earendil-works/pi-coding-agent";
import { Key, matchesKey, visibleWidth } from "@earendil-works/pi-tui";
import { createCursorController } from "./cursor.ts";
import {
  canRemapNavigation,
  handleNormalHorizontalMotion,
  handleVisualLineRemap,
} from "./navigation.ts";
import { handleVisualPaste } from "./visual-paste.ts";
import {
  applyPromptHistory,
  hydratePromptHistory,
  replacePromptHistory,
} from "./prompt-history.ts";

const INSERT_PREFIX = "❯ ";
const NORMAL_PREFIX = "❮ ";
const CONTINUATION_PREFIX = "  ";
const PREFIX_WIDTH = visibleWidth(INSERT_PREFIX);
const ANSI_COLOR_RE = /\x1b\[[0-9;]*m/g;
const EXTENSION_DIR =
  typeof __dirname === "string" ? __dirname : dirname(fileURLToPath(import.meta.url));
// pi's extension loader can evaluate TS via jiti, but importing pi-vim directly
// is not reliable in this extension context. We generate a tiny local wrapper
// that re-exports the pi-managed pi-vim entry and import that instead.
const PI_VIM_WRAPPER = join(EXTENSION_DIR, "pi-vim.generated.ts");
// pi-vim mirrors these because Pi does not expose its builtin interactive
// command registry. Keep this list aligned with pi-vim's EX_BUILTIN_COMMAND_NAMES.
const PI_VIM_BUILTIN_COMMAND_NAMES = [
  "settings",
  "model",
  "thinking",
  "scoped-models",
  "export",
  "import",
  "share",
  "bug",
  "copy",
  "name",
  "session",
  "changelog",
  "hotkeys",
  "fork",
  "clone",
  "tree",
  "login",
  "logout",
  "new",
  "compact",
  "resume",
  "reload",
  "quit",
  "trust",
] as const;

function findPiVimEntry(): string {
  // pi manages its own npm packages at <agent-dir>/npm/node_modules.
  // Use getAgentDir() to resolve the pi-managed installation (updated via
  // `pi install npm:pi-vim`).
  const entry = join(getAgentDir(), "npm", "node_modules", "pi-vim", "index.ts");
  if (existsSync(entry)) return entry;

  throw new Error("prompt-editor: pi-vim not found. Install with: pi install npm:pi-vim");
}

function ensurePiVimWrapper(): void {
  // Keep the generated wrapper in sync with the installed pi-vim version so
  // the extension remains self-contained and does not require a manual setup step.
  const piVimEntry = findPiVimEntry();
  const piVimDir = dirname(piVimEntry);
  const content = `/**
 * Auto-generated by prompt-editor/index.ts.
 * Do not edit manually.
 */

export * from ${JSON.stringify(piVimEntry)};
export { resolveClipboardMirrorPolicy } from ${JSON.stringify(join(piVimDir, "clipboard-policy.ts"))};
export { cancelModeChangeCommands, createModeChangeHandler } from ${JSON.stringify(join(piVimDir, "mode-change-command.ts"))};
export { buildModeColorizers, buildOffBorderColor, resolveModeColors } from ${JSON.stringify(join(piVimDir, "mode-colors.ts"))};
export { CURSOR_SHAPE_SEQUENCES } from ${JSON.stringify(join(piVimDir, "cursor-shape.ts"))};
export { createCursorBindingResolver } from ${JSON.stringify(join(piVimDir, "input-keys.ts"))};
export { readPiVimSettings, resolveCursorShapeSettings, resolveExCommandSettings, resolveHistoryNavigation, resolveLabelPosition, resolveSurfaceSyncMaps } from ${JSON.stringify(join(piVimDir, "settings.ts"))};
`;

  const current = existsSync(PI_VIM_WRAPPER) ? readFileSync(PI_VIM_WRAPPER, "utf8") : null;
  if (current !== content) {
    writeFileSync(PI_VIM_WRAPPER, content);
  }
}

export default async function (pi: ExtensionAPI) {
  ensurePiVimWrapper();

  const {
    ModalEditor,
    CURSOR_SHAPE_SEQUENCES,
    createCursorBindingResolver,
    buildModeColorizers,
    buildOffBorderColor,
    cancelModeChangeCommands,
    createModeChangeHandler,
    readPiVimSettings,
    resolveClipboardMirrorPolicy,
    resolveCursorShapeSettings,
    resolveExCommandSettings,
    resolveHistoryNavigation,
    resolveLabelPosition,
    resolveModeColors,
    resolveSurfaceSyncMaps,
  } = await import("./pi-vim.generated.ts");

  type Mode = "insert" | "normal" | "visual" | "visual-line";
  type ModalEditorConstructorArgs = ConstructorParameters<typeof ModalEditor>;
  type EditorFactory = NonNullable<Parameters<ExtensionUIContext["setEditorComponent"]>[0]>;
  type EditorFactoryArgs = Parameters<EditorFactory>;

  type ModeColorKey = "insert" | "normal" | "visual" | "ex";
  type ModeColorizers = Record<ModeColorKey, (s: string) => string>;
  type SurfaceSync = "mode" | "host" | "thinking";
  type SurfaceSyncMap = Record<ModeColorKey, SurfaceSync>;

  type ModalEditorRuntime = {
    getMode: () => Mode;
    setMode?: (mode?: Mode) => void;
    borderColor?: (s: string) => string;
    pendingExCommand: string | null;
    pendingOperator: string | null;
    pendingG: boolean;
    pendingGCount: string;
    discardingBracketedPasteInNormalMode: boolean;
    cancelAutocomplete: () => void;
    addToHistory?: (text: string) => void;
    history?: string[];
    historyIndex?: number;
  };

  function findBottomBorderIndex(lines: string[]): number {
    for (let i = lines.length - 1; i >= 0; i--) {
      const stripped = lines[i]!.replace(ANSI_COLOR_RE, "");
      if (stripped.startsWith("─")) return i;
    }
    return -1;
  }

  // Related upstream logic:
  // - https://github.com/lajarre/pi-vim/blob/2671cf11/index.ts (ModalEditor.render + getModeLabel + getModeLabelColorizer)
  function getActiveMode(editor: ModalEditorRuntime): ModeColorKey {
    if (editor.pendingExCommand !== null) return "ex";
    const mode = editor.getMode();
    return mode === "visual-line" ? "visual" : mode;
  }

  function getRenderedPrefix(editor: ModalEditorRuntime, colorizers: ModeColorizers): string {
    const mode = editor.getMode();
    const prefix = mode === "insert" ? INSERT_PREFIX : NORMAL_PREFIX;
    const active = getActiveMode(editor);
    const colorize = colorizers[active];

    return colorize ? colorize(prefix) : prefix;
  }

  type EditorUI = {
    setEditorComponent: ExtensionUIContext["setEditorComponent"];
  };

  type PromptHistory = Parameters<typeof hydratePromptHistory>[1];

  const cursor = createCursorController();
  let activeUi: EditorUI | undefined;

  let originalSetEditorComponent: EditorUI["setEditorComponent"] | undefined;
  let reinstallTimer: NodeJS.Timeout | undefined;
  let sessionGeneration = 0;

  class PromptEditor extends ModalEditor {
    private readonly prefixColorizers: ModeColorizers;
    private readonly resolveCursorMotion: ReturnType<typeof createCursorBindingResolver>;

    constructor(
      tui: EditorFactoryArgs[0],
      theme: EditorFactoryArgs[1],
      kb: EditorFactoryArgs[2],
      labelColorizers: ModeColorizers | null,
      borderColorizers: ModeColorizers | null,
      borderSync: SurfaceSyncMap,
      labelSync: SurfaceSyncMap,
      offBorderColor: ((s: string) => string) | null,
      labelTransform: (s: string) => string,
      prefixColorizers: ModeColorizers,
      labelPosition: "bottom-right" | "top-left",
      selectionColorizer: (s: string) => string,
    ) {
      super(
        tui as unknown as ModalEditorConstructorArgs[0],
        theme as unknown as ModalEditorConstructorArgs[1],
        kb as unknown as ModalEditorConstructorArgs[2],
        {
          labelColorizers,
          borderColorizers,
          borderSync,
          labelSync,
          offBorderColor,
          labelTransform,
          labelPosition,
          selectionColorizer,
        },
      );
      this.prefixColorizers = prefixColorizers;
      this.resolveCursorMotion = createCursorBindingResolver(
        kb as unknown as ModalEditorConstructorArgs[2],
      );
      // Pi 0.85 added embedWorkingStatus on CustomEditor. pi-vim's
      // ModalEditor doesn't forward options to super(), so set it directly.
      (this as any).embedWorkingStatus = true;
      // pi-vim has built-in cursor shape management
      // (https://github.com/lajarre/pi-vim/blob/2671cf11/index.ts)
      // that conflicts with our DECSCUSR logic. Disable it so
      // our cursor controller is the sole cursor authority.
      (this as any).cursorShapeRuntime = null;
    }

    override handleInput(data: string): void {
      const runtime = this as unknown as ModalEditorRuntime;
      if (!this.preflightHost()) {
        super.handleInput(data);
        return;
      }
      // Explicit Normal-mode gj aliases J; synthetic j -> gj calls super directly.
      if (
        this.getMode() === "normal" &&
        data === "j" &&
        runtime.pendingG &&
        runtime.pendingGCount === "" &&
        runtime.pendingOperator === null &&
        runtime.pendingExCommand === null &&
        !runtime.discardingBracketedPasteInNormalMode
      ) {
        // Keep the prefix count, but let upstream record and replay a canonical J.
        runtime.pendingG = false;
        super.handleInput("J");
        return;
      }
      // Preserve local cl -> s; upstream still lacks horizontal change motions.
      if (runtime.pendingOperator === "c" && data === "l" && canRemapNavigation(this, true)) {
        runtime.pendingOperator = null;
        super.handleInput("s");
        return;
      }
      // Upstream owns degradation, EX, paste and pending arguments (including Z).
      if (!canRemapNavigation(this)) {
        const completesLineChange =
          this.getMode() === "normal" &&
          runtime.pendingOperator === "c" &&
          data === "c" &&
          canRemapNavigation(this, true);
        super.handleInput(data);
        if (completesLineChange && this.getMode() === "insert") {
          // Upstream cc calls host deletion directly, leaving the old picker alive.
          // Cancel through Pi so both visible UI and in-flight requests are cleared.
          runtime.cancelAutocomplete();
        }
        return;
      }
      const mode = this.getMode();
      const submittedFromNormalMode =
        mode === "normal" &&
        data !== "\n" &&
        matchesKey(data, Key.enter) &&
        this.getText().trim() !== "";
      if (mode === "normal") {
        // Backspace in normal mode: map to h (move left) instead of
        // passing through to the base Editor which deletes a character.
        if (matchesKey(data, Key.backspace)) {
          if (!handleNormalHorizontalMotion(this, "h")) super.handleInput("h");
          return;
        }
        // React when Ctrl+C clears the input: auto-enter insert mode so
        // the user can start typing immediately.
        if (matchesKey(data, Key.ctrl("c"))) {
          super.handleInput(data);
          if (this.getText() === "") {
            (this as unknown as ModalEditorRuntime).setMode?.("insert");
          }
          return;
        }
        // U -> Ctrl+r
        if (data === "U") {
          super.handleInput("\x12");
          return;
        }
        // Y -> y$
        if (data === "Y") {
          super.handleInput("y");
          super.handleInput("$");
          return;
        }
      }
      if (mode !== "insert") {
        // Match upstream cursor aliases, preserving modal Escape and Vim undo/redo.
        const vimControl =
          matchesKey(data, "escape") ||
          matchesKey(data, "ctrl+[") ||
          matchesKey(data, "ctrl+r") ||
          matchesKey(data, "ctrl+_");
        const motion = vimControl ? data : (this.resolveCursorMotion(data) ?? data);
        if (mode === "normal" && handleNormalHorizontalMotion(this, motion)) return;
        if ((mode === "visual" || mode === "visual-line") && handleVisualPaste(this, data)) return;
        if (motion === "j" || motion === "k") {
          // Let upstream own wrapped layout, wanted columns, counts and replay.
          super.handleInput("g");
          super.handleInput(motion);
          return;
        }
        if (handleVisualLineRemap(this, motion)) return;
      }
      super.handleInput(data);
      if (submittedFromNormalMode && this.getText() === "") {
        // Enter clears the editor synchronously only when it submitted rather
        // than accepted autocomplete. Start the next prompt in insert mode.
        (this as unknown as ModalEditorRuntime).setMode?.("insert");
      }
    }

    override render(width: number): string[] {
      if (!this.preflightHost()) return super.render(width);
      cursor.syncPreference(this.getMode());

      if (width <= PREFIX_WIDTH) {
        const lines = super.render(width);
        const bottomIdx = findBottomBorderIndex(lines);
        // Last line has ModalEditor's mode label; don't strip its inverse-video.
        cursor.render(lines, bottomIdx >= 1 ? bottomIdx : lines.length - 1);
        return lines;
      }

      // Upstream owns selection paint, labels, preflight and gj/gk layout tracking.
      // The top-left label stays on the border even when autocomplete is visible.
      const lines = super.render(width - PREFIX_WIDTH);
      if (lines.length < 3) {
        cursor.render(lines, lines.length);
        return lines;
      }

      const bottomIdx = findBottomBorderIndex(lines);
      if (bottomIdx <= 0) {
        cursor.render(lines, lines.length);
        return lines;
      }

      const borderColor = this.borderColor ?? ((s: string) => s);
      const extraBorder = borderColor("─".repeat(PREFIX_WIDTH));
      const renderedPrefix = getRenderedPrefix(
        this as unknown as ModalEditorRuntime,
        this.prefixColorizers,
      );

      // The editor body is rendered `PREFIX_WIDTH` columns narrower so wrapped
      // text accounts for the prompt prefix. We then extend the top/bottom
      // borders back to the full terminal width and prefix only the body lines.
      // With embedWorkingStatus the spinner lives inside the top border's left
      // region (before its trailing border run), so extending on the right
      // keeps it intact.
      lines[0] = lines[0]! + extraBorder;
      lines[bottomIdx] = lines[bottomIdx]! + extraBorder;

      for (let i = 1; i < bottomIdx; i++) {
        lines[i] = (i === 1 ? renderedPrefix : CONTINUATION_PREFIX) + lines[i]!;
      }

      cursor.render(lines, bottomIdx);
      return lines;
    }
  }

  const offMyFocusChange = pi.events.on("my:focus_change", (data: unknown) => {
    const { focused } = data as { focused: boolean };
    cursor.setFocused(focused);
  });

  pi.on("session_start", (_event, ctx) => {
    // Mirror pi-vim's session initialization because PromptEditor replaces the
    // editor instance configured by pi-vim's own session_start handler.
    const piVimSettings = readPiVimSettings(ctx.cwd);
    const clipboardMirrorPolicy = resolveClipboardMirrorPolicy(piVimSettings.clipboardMirror);
    const exCommand = resolveExCommandSettings(
      piVimSettings.exCommand,
      piVimSettings.globalExCommand,
    );

    const historyNavigation = resolveHistoryNavigation(piVimSettings.historyNavigation);
    const cursorShape = resolveCursorShapeSettings(piVimSettings.cursorShape);
    const labelPosition = resolveLabelPosition(piVimSettings.labelPosition);
    for (const warning of [
      clipboardMirrorPolicy.warning,
      exCommand.warning,
      historyNavigation.warning,
      cursorShape.warning,
      labelPosition.warning,
    ]) {
      if (warning && ctx.hasUI) ctx.ui.notify(warning, "warning");
    }
    cursor.setShapeSequences({
      insert: CURSOR_SHAPE_SEQUENCES[cursorShape.settings.insert],
      normal: CURSOR_SHAPE_SEQUENCES[cursorShape.settings.normal],
    });

    const theme = ctx.ui.theme;
    const modeColors = resolveModeColors(piVimSettings.modeColors);
    const reverseVideo = (s: string) => `\x1b[7m${s}\x1b[27m`;
    const { borderSync, labelSync } = resolveSurfaceSyncMaps(piVimSettings);
    const colorizers: ModeColorizers = buildModeColorizers(theme, modeColors, reverseVideo);
    const borderColorizers: ModeColorizers = buildModeColorizers(theme, modeColors);
    const offBorderColor = buildOffBorderColor(theme);
    // Insert always stays plain. For other modes, a prefix remains colored
    // unless the border is guaranteed to carry that mode's color.
    const plainPrefix = (s: string) => s;
    const prefixColorizers: ModeColorizers = buildModeColorizers(theme, modeColors);
    prefixColorizers.insert = plainPrefix;
    for (const mode of ["normal", "visual", "ex"] as const) {
      if (borderSync[mode] === "mode") prefixColorizers[mode] = plainPrefix;
    }
    const modeChangeHandler = createModeChangeHandler(
      piVimSettings.modeChange,
      (event: { mode: Mode; previousMode: Mode }) => {
        pi.events.emit("pi-vim:mode-change", event);
        cursor.modeChanged(event.mode);
      },
    );

    // Related upstream logic:
    // - https://github.com/lajarre/pi-vim/blob/2671cf11/index.ts (default export session_start handler)
    // - https://github.com/badlogic/pi-mono/blob/cca5a3a1a4c6db90e4c5e2e95772845c1d5a251d/packages/coding-agent/src/modes/interactive/interactive-mode.ts#L1841-L1909 (setCustomEditorComponent)
    //
    // prompt-editor loads from the user extension directory, while pi-vim is a
    // package extension and can run later in session_start. Do not rely only on
    // setTimeout(0): any earlier async session_start handler can yield to timers
    // before pi-vim installs its editor. Wrap setEditorComponent for this session
    // so any later editor install is followed by re-installing our PromptEditor
    // subclass.
    const generation = ++sessionGeneration;
    if (reinstallTimer) {
      clearTimeout(reinstallTimer);
      reinstallTimer = undefined;
    }

    const ui = ctx.ui as unknown as EditorUI;
    if (!originalSetEditorComponent || activeUi !== ui) {
      originalSetEditorComponent = ui.setEditorComponent.bind(ctx.ui);
      activeUi = ui;
    }

    let editor: ModalEditorRuntime | undefined;
    let reinstallPromptEditor: (() => void) | undefined;
    let installingPromptEditor = false;
    const isCurrentSession = () => generation === sessionGeneration;

    const installPromptEditor = (history: PromptHistory) => {
      if (!isCurrentSession()) return;
      // The startup snapshot misses prompts added or loaded since installation.
      // This editor reference belongs to this session, not the competing editor.
      const retainedHistory = editor?.history?.slice();
      originalSetEditorComponent?.((tui, editorTheme, kb) => {
        const newEditor = new PromptEditor(
          tui,
          editorTheme,
          kb,
          colorizers,
          borderColorizers,
          borderSync,
          labelSync,
          offBorderColor,
          reverseVideo,
          prefixColorizers,
          labelPosition.position,
          (text) => {
            try {
              const painted = ctx.ui.theme.bg("selectedBg", text);
              if (painted !== text && painted !== `\x1b[49m${text}\x1b[49m`) return painted;
            } catch {
              // Incomplete themes retain upstream's reverse-video fallback.
            }
            return reverseVideo(text);
          },
        );

        // pi-vim configures quitFn and notifyFn on the editor
        // (https://github.com/lajarre/pi-vim/blob/2671cf11/index.ts).
        // Apply them to our subclass so :q/:wq etc work correctly.
        newEditor.setClipboardMirrorPolicy(clipboardMirrorPolicy.policy);
        newEditor.setQuitFn(() => ctx.shutdown());
        newEditor.setNotifyFn((message: string) => ctx.ui.notify(message, "warning"));
        newEditor.setModeChangeFn(modeChangeHandler);
        newEditor.setHistoryNavigation(historyNavigation.enabled);
        newEditor.setCursorShapeSettings(cursorShape.settings);
        newEditor.setExCommandSettings(exCommand.settings);
        // Resolve at submit time so commands registered or reloaded during the
        // session become available without reinstalling the editor.
        newEditor.setCommandNamesFn(
          () =>
            new Set([
              ...PI_VIM_BUILTIN_COMMAND_NAMES,
              ...pi.getCommands().map((command) => command.name),
            ]),
        );
        editor = newEditor as unknown as ModalEditorRuntime;
        // Match Pi's effective preference, not a competing editor's forced visibility.
        const showHardwareCursor =
          pi.getSettings().showHardwareCursor ?? process.env.PI_HARDWARE_CURSOR === "1";
        if (newEditor.preflightHost()) {
          cursor.install(tui, newEditor, showHardwareCursor);
        } else {
          cursor.release();
          tui.setShowHardwareCursor(showHardwareCursor);
        }

        if (retainedHistory) {
          editor.history = retainedHistory;
          editor.historyIndex = -1;
        } else {
          hydratePromptHistory(editor, history);
        }
        return newEditor;
      });

      if (editor) {
        // Must run after setEditorComponent() returns: interactive-mode
        // overwrites newEditor.borderColor during the swap.
        editor.borderColor = ctx.ui.theme.getThinkingBorderColor(pi.getThinkingLevel());
      }
    };

    const scheduleReinstall = () => {
      if (!reinstallPromptEditor || reinstallTimer || !isCurrentSession()) return;
      reinstallTimer = setTimeout(() => {
        reinstallTimer = undefined;
        if (isCurrentSession()) reinstallPromptEditor?.();
      }, 0);
    };

    ui.setEditorComponent = ((factory: EditorFactory | undefined) => {
      originalSetEditorComponent?.(factory);
      if (!installingPromptEditor) {
        scheduleReinstall();
      }
    }) satisfies EditorUI["setEditorComponent"];

    applyPromptHistory(
      ctx,
      (history) => {
        reinstallPromptEditor = () => {
          if (!isCurrentSession()) return;
          installingPromptEditor = true;
          try {
            installPromptEditor(history);
          } finally {
            installingPromptEditor = false;
          }
        };

        reinstallPromptEditor();
      },
      (history) => {
        if (!editor) return;
        replacePromptHistory(editor, history);
      },
    );
  });

  pi.on("session_shutdown", () => {
    sessionGeneration++;
    if (reinstallTimer) {
      clearTimeout(reinstallTimer);
      reinstallTimer = undefined;
    }

    if (activeUi && originalSetEditorComponent) {
      activeUi.setEditorComponent = originalSetEditorComponent;
    }
    offMyFocusChange();
    cancelModeChangeCommands();
    activeUi = undefined;
    originalSetEditorComponent = undefined;
    cursor.shutdown();
  });
}
